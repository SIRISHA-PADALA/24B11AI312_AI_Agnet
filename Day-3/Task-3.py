import os
import csv
from pathlib import Path

from google.colab import userdata

from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser
from langchain.agents import create_agent


api_key = userdata.get("GROQ_API_KEY")

if not api_key:
    raise ValueError("GROQ_API_KEY is missing. Add it in Colab Secrets.")

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0.3,
    api_key=api_key
)

print("StudyMate AI connected successfully!")

SYSTEM = """
ROLE:
You are StudyMate AI, a friendly and helpful study planning assistant
for college students.

YOU CAN HELP WITH:
- Creating personalized daily and weekly study plans.
- Managing study time effectively.
- Explaining difficult subjects and topics.
- Helping students prepare for examinations.
- Suggesting revision strategies.
- Tracking learning progress and study goals.
- Motivating students to study consistently.

RULES:
- Give simple and beginner-friendly explanations.
- Create realistic study schedules.
- Consider the student's available study hours.
- Give priority to weak subjects and difficult topics.
- Do not overload students with unrealistic schedules.
- Encourage regular revision and practice.
- Ask follow-up questions when important information is missing.

FORMAT:
Be friendly, supportive, and concise.
Reply in English or Telugu according to the student's language.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

print("StudyMate AI chain created successfully!")

history = []

def ask(question: str) -> str:
    """Send a question to StudyMate AI and remember the conversation."""

    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

def demo_chat():

    print("\n--- StudyMate AI: Conversation Demo ---")

    print("Student: My name is Siri. I am preparing for Python and DSA.")

    print("StudyMate AI:", ask(
        "My name is Siri. I am preparing for Python and DSA."
    ))

    print("\nStudent: Which subjects am I preparing for?")

    print("StudyMate AI:", ask(
        "Which subjects am I preparing for?"
    ))


demo_chat()

test_data = [
    ["question", "must_include"],
    ["Create a study plan for Python", "Python"],
    ["How can I manage my study time?", "time"],
    ["Why is revision important?", "revision"],
    ["How can I improve my weak topics?", "practice"]
]

with open("studymate_test.csv", "w", newline="", encoding="utf-8") as file:
    writer = csv.writer(file)
    writer.writerows(test_data)

print("StudyMate test cases created successfully!")

def run_tests(path="studymate_test.csv"):

    csv_path = Path(path)

    if not csv_path.exists():
        print("Test file not found!")
        return

    with csv_path.open("r", encoding="utf-8", newline="") as file:
        rows = list(csv.DictReader(file))

    if not rows:
        print("No test cases found!")
        return

    passed = 0

    print("\n--- StudyMate AI: Evaluation Results ---")

    for row in rows:

        question = row["question"]
        expected = row["must_include"]

        answer = chain.invoke({
            "history": [],
            "question": question
        })

        success = expected.lower() in answer.lower()

        if success:
            passed += 1

        print(
            ("PASS" if success else "FAIL"),
            "|",
            question,
            "->",
            answer[:120].replace("\n", " ")
        )

    percentage = (passed / len(rows)) * 100

    print(f"\n{passed}/{len(rows)} tests passed ({percentage:.0f}%).")


run_tests()

def agent_demo():

    print("\n--- StudyMate AI: Agent Foundation ---")

    agent = create_agent(
        model=llm,
        tools=[],
        system_prompt=SYSTEM
    )

    result = agent.invoke({
        "messages": [
            {
                "role": "user",
                "content": "Create a simple 3-hour daily study plan for Python and DSA."
            }
        ]
    })

    print(result["messages"][-1].content)


agent_demo()

