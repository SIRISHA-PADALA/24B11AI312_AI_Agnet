import os
from google.colab import userdata

from langchain_groq import ChatGroq
from sentence_transformers import SentenceTransformer
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser

import fitz
import numpy as np
import faiss

os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")

llm = ChatGroq(
    model="openai/gpt-oss-20b",
    temperature=0.2
)

print("Groq connected successfully!")

from google.colab import files
import pymupdf

uploaded = files.upload()

pdf_path = list(uploaded.keys())[0]

document = pymupdf.open(pdf_path)

pdf_text = ""

for page in document:
    pdf_text += page.get_text()

print("PDF uploaded successfully!")
print("Total pages:", len(document))
print("Extracted characters:", len(pdf_text))

print("\nPDF Text Preview:\n")
print(pdf_text[:1500])

text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=1000,
    chunk_overlap=200
)

chunks = text_splitter.split_text(pdf_text)

print("Total chunks:", len(chunks))
print("\nFirst chunk:\n")
print(chunks[0])

embedding_model = SentenceTransformer("all-MiniLM-L6-v2")

embeddings = embedding_model.encode(chunks)

print("Embeddings generated successfully!")
print("Embedding shape:", embeddings.shape)

dimension = embeddings.shape[1]

index = faiss.IndexFlatL2(dimension)

index.add(np.array(embeddings).astype("float32"))

print("FAISS vector database created successfully!")
print("Total vectors stored:", index.ntotal)

query = "What are Python data types?"

query_embedding = embedding_model.encode([query])

distances, indices = index.search(
    np.array(query_embedding).astype("float32"),
    k=3
)

print("User Question:", query)
print("\nRelevant PDF Content:\n")

for i in indices[0]:
    print(chunks[i])
    print("-" * 50)

question = "What are Python data types?"

context = "\n\n".join(
    [chunks[i] for i in indices[0]]
)

prompt = f"""
Answer the question using only the context below.

Context:
{context}

Question:
{question}

Give a clear and beginner-friendly answer.
"""

response = llm.invoke(prompt)

print("Question:", question)
print("\nAI Answer:\n")
print(response.content)

