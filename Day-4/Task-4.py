@tool
def log_study_progress(
    student: str,
    subject: str,
    topic: str,
    study_hours: float,
    status: str
) -> str:
    """Validates and saves student study progress to Google Sheets."""

    try:
        progress = StudyProgress(
            student=student,
            subject=subject.lower().strip(),
            topic=topic,
            study_hours=study_hours,
            status=status.lower().strip()
        )

        ws.append_row([
            progress.student,
            progress.subject,
            progress.topic,
            progress.study_hours,
            progress.status
        ])

        return "Study progress saved successfully to Google Sheets!"

    except Exception as e:
        return f"Could not save progress: {str(e)}"


