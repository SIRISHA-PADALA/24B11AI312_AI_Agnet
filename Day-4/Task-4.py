from langchain_core.tools import tool

# --------------------------------
# 1. Subject Guidance Tool
# --------------------------------

@tool
def get_subject_guidance(subject: str) -> str:
    """Provides topics and learning advice for a selected subject."""

    subject = subject.lower().strip()

    if subject not in SUBJECTS:
        return "Subject not available. Choose Python, Data Structures, Machine Learning, or Mathematics."

    details = SUBJECTS[subject]

    return (
        f"Subject: {subject.title()}\n"
        f"Description: {details['description']}\n"
        f"Important Topics: {', '.join(details['topics'])}\n"
        f"Advice: {details['advice']}"
    )


# --------------------------------
# 2. Study Plan Creation Tool
# --------------------------------

@tool
def create_study_plan(
    subjects: str,
    hours: float,
    weak_topics: str
) -> str:
    """Creates a study plan based on subjects, available hours, and weak topics."""

    if hours <= 0:
        return "Please provide study hours greater than zero."

    subject_list = [s.strip() for s in subjects.split(",") if s.strip()]
    weak_topic_list = [t.strip() for t in weak_topics.split(",") if t.strip()]

    if not subject_list:
        return "Please provide at least one subject."

    minutes_per_subject = (hours * 60) / len(subject_list)

    plan = f"Your {hours}-hour study plan:\n\n"

    for subject in subject_list:
        plan += (
            f"- {subject.title()}: "
            f"{minutes_per_subject:.0f} minutes\n"
        )

    if weak_topic_list:
        plan += "\nFocus more on these weak topics:\n"
        for topic in weak_topic_list:
            plan += f"- {topic}\n"

    plan += "\nRemember to take short breaks between study sessions."

    return plan


