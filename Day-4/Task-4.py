history = []


# --------------------------------
# 4. Chat Function
# --------------------------------

def chat(question):

    history.append(HumanMessage(content=question))

    response = agent.invoke({
        "messages": history
    })

    history.clear()
    history.extend(response["messages"])

    answer = response["messages"][-1].content

    print("\nStudyMate AI:")
    print(answer)


